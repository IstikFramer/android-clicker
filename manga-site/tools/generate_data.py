def slug_to_seed(slug):
    return sum(ord(c) * (i + 7) for i, c in enumerate(slug)) + 13


def make_chapters(rng, mtype, status, year, count):
    # главы раскладываются от «сегодня» назад; у старых тайтлов часть истории
    # уходит в прошлое, поэтому дата первой главы может быть раньше года старта —
    # это нормально для демо-данных.
    chapters = []
    days_back = 0
    for i in range(count, 0, -1):
        is_extra = i > 1 and rng.random() < 0.07  # «экстра» не может быть первой главой
        if is_extra:
            number = f"{i}.5"
        else:
            number = str(i)
        days_back += rng.randint(2, 9)
        date = (TODAY - datetime.timedelta(days=days_back)).isoformat()
        title = rng.choice(CHAPTER_TITLE_WORDS)
        chapters.append({
            "number": number,
            "title": title,
            "volume": max(1, (i - 1) // 10 + 1),
            "date": date,
            "views": int(20000 + rng.random() * 180000),
            "pages": rng.randint(18, 62),
            "kind": "extra" if is_extra else "chapter",
        })
    # сортируем по номеру главы численно, чтобы «экстры» (1.5, 2.5) стояли на своих местах
    chapters.sort(key=lambda c: float(c["number"]))
    if status == "anons":
        chapters = []
    return chapters


