let currentLang = 'ru';

export function setLanguage(lang) {
  if (DICT[lang]) currentLang = lang;
  else if (lang && lang.startsWith('en')) currentLang = 'en';
  else if (lang && lang.startsWith('tr')) currentLang = 'tr';
  else if (lang && lang.startsWith('ru')) currentLang = 'ru';
  else currentLang = 'en';
}

export function t(key) {
  return (DICT[currentLang] && DICT[currentLang][key]) || DICT.en[key] || key;
}

export function getLanguage() {
  return currentLang;
}

